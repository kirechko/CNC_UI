//! Versioned, user-authored machine profile records kept separately from live controller telemetry.
//!
//! Profiles intentionally have no discovered-device identity binding yet: endpoint identities are
//! not stable enough to assert the roadmap's one-profile-per-physical-controller acceptance gate.

use rusqlite::{params, Connection, OptionalExtension, TransactionBehavior};
use serde::{Deserialize, Serialize};
use std::collections::HashSet;

/// Read-only resolver for profile metadata and cached controller configuration.
pub mod resolution;

pub use resolution::ResolvedConfiguration;

/// Current portable JSON document version for machine profile import and export.
pub(crate) const PROFILE_DOCUMENT_VERSION: u32 = 1;

/// User-authored machine configuration. Missing axis bounds remain unknown rather than being
/// inferred from an adapter or replaced with a permissive numeric default.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct MachineProfile {
    /// Stable local profile id generated by the client or imported from an export document.
    pub id: String,
    /// Human-readable profile label shown in local profile management.
    pub name: String,
    /// Machine category; this is descriptive metadata, not a firmware capability assertion.
    pub machine_type: MachineType,
    /// Explicit units used by all user-authored dimensional values in this record.
    #[serde(default)]
    pub units: Units,
    /// Optional axis travel bounds. `None` means unknown and must not be treated as unbounded-safe.
    #[serde(default)]
    pub travel: AxisTravel,
    /// Optional user-entered maximum axis speeds; these are metadata, not controller settings.
    #[serde(default)]
    pub speeds: AxisSpeeds,
    /// Optional spindle or laser configuration entered by the user, not measured controller state.
    #[serde(default)]
    pub power: Option<PowerProfile>,
    /// Per-field user preferences for choosing profile or cached controller metadata when both exist.
    #[serde(default)]
    pub source_priorities: SourcePriorities,
    /// Optional stable local tool-library id associated with this machine profile.
    #[serde(default)]
    pub tool_reference: Option<String>,
    /// Reserved versioned extension space for later calibration/material work; opaque data is
    /// preserved on import/export but is never interpreted as a safety guarantee.
    #[serde(default)]
    pub extensions: serde_json::Value,
    /// Timestamp in Unix milliseconds when this profile was first persisted locally.
    pub created_at_ms: i64,
    /// Timestamp in Unix milliseconds when this profile was last changed locally.
    pub updated_at_ms: i64,
}

/// Preferred metadata source when both profile and controller values are available.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SourcePriority {
    /// Prefer user-authored profile metadata, falling back to controller data when absent.
    ProfileFirst,
    /// Prefer cached controller metadata, falling back to profile data when absent.
    ControllerFirst,
}

impl Default for SourcePriority {
    /// Defaults to profile-first to preserve the existing resolver's precedence.
    fn default() -> Self {
        Self::ProfileFirst
    }
}

/// Per-field source preferences persisted with the user-authored profile.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct SourcePriorities {
    /// Preferred source for the descriptive machine category.
    #[serde(default)]
    pub machine_type: SourcePriority,
    /// Preferred source for configured linear-axis availability.
    #[serde(default)]
    pub axes: SourcePriority,
    /// Preferred source for dimensional units.
    #[serde(default)]
    pub units: SourcePriority,
    /// Preferred source for axis travel limits.
    #[serde(default)]
    pub travel: SourcePriority,
    /// Preferred source for maximum axis speeds.
    #[serde(default)]
    pub speeds: SourcePriority,
    /// Preferred source for process output limits.
    #[serde(default)]
    pub power: SourcePriority,
}

/// User-entered maximum speeds for the linear X, Y and Z axes, in profile units per minute.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct AxisSpeeds {
    /// Maximum configured X-axis speed, or unknown when omitted.
    pub x: Option<f64>,
    /// Maximum configured Y-axis speed, or unknown when omitted.
    pub y: Option<f64>,
    /// Maximum configured Z-axis speed, or unknown when omitted.
    pub z: Option<f64>,
}

/// Broad machine category used for organization and future workflow selection.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MachineType {
    /// Subtractive machine primarily using rotary cutting tools.
    Mill,
    /// Machine primarily using a laser process.
    Laser,
    /// Machine configured for both milling and laser work.
    Hybrid,
}

/// Dimensional unit declaration for values in a machine profile.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum Units {
    /// Millimeter dimensional values.
    #[default]
    Millimeters,
    /// Inch dimensional values.
    Inches,
}

/// User-supplied minimum and maximum travel for the three linear axes.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct AxisTravel {
    /// Known X minimum, or `None` if not configured.
    pub x_min: Option<f64>,
    /// Known X maximum, or `None` if not configured.
    pub x_max: Option<f64>,
    /// Known Y minimum, or `None` if not configured.
    pub y_min: Option<f64>,
    /// Known Y maximum, or `None` if not configured.
    pub y_max: Option<f64>,
    /// Known Z minimum, or `None` if not configured.
    pub z_min: Option<f64>,
    /// Known Z maximum, or `None` if not configured.
    pub z_max: Option<f64>,
}

/// Optional process output limits entered by the user for this machine.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct PowerProfile {
    /// Declares whether values refer to spindle speed or laser power.
    pub kind: PowerKind,
    /// Lowest configured command value, if explicitly known.
    pub min: Option<f64>,
    /// Highest configured command value, if explicitly known.
    pub max: Option<f64>,
}

/// Process output category carried by a user-authored profile.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PowerKind {
    /// Rotational spindle speed, in the machine's configured command units.
    Spindle,
    /// Laser output command scale, which still requires controller-specific validation.
    Laser,
}

/// JSON document used for lossless profile export and validated import.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct MachineProfileDocument {
    /// Schema version required to interpret the document.
    pub schema_version: u32,
    /// Profiles contained in this portable document.
    pub profiles: Vec<MachineProfile>,
}

/// Creates the profile table and version marker without changing existing legacy tables.
pub fn ensure_schema(connection: &Connection) -> Result<(), String> {
    connection
        .execute_batch(
            "CREATE TABLE IF NOT EXISTS machine_profiles (
                id TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                document_json TEXT NOT NULL,
                created_at_ms INTEGER NOT NULL,
                updated_at_ms INTEGER NOT NULL
             );
             CREATE UNIQUE INDEX IF NOT EXISTS machine_profiles_name_unique
                ON machine_profiles(name COLLATE NOCASE);
             CREATE TABLE IF NOT EXISTS app_schema_migrations (
                name TEXT PRIMARY KEY,
                applied_at_ms INTEGER NOT NULL
             );
             CREATE TABLE IF NOT EXISTS machine_profile_settings (
                key TEXT PRIMARY KEY,
                value TEXT
             );
             INSERT OR IGNORE INTO app_schema_migrations(name, applied_at_ms)
                VALUES ('machine_profiles_v1', 0);",
        )
        .map_err(|error| format!("cannot initialize machine profile schema: {error}"))
}

/// Lists persisted profiles by case-insensitive name and stable id for deterministic UI ordering.
pub fn list(connection: &Connection) -> Result<Vec<MachineProfile>, String> {
    let mut statement = connection
        .prepare("SELECT document_json FROM machine_profiles ORDER BY name COLLATE NOCASE, id")
        .map_err(|error| error.to_string())?;
    let rows = statement
        .query_map([], |row| row.get::<_, String>(0))
        .map_err(|error| error.to_string())?;
    rows.map(|row| {
        let json = row.map_err(|error| error.to_string())?;
        serde_json::from_str(&json).map_err(|error| format!("corrupt machine profile: {error}"))
    })
    .collect()
}

/// Inserts or updates one validated profile atomically, preserving original creation time on update.
pub fn upsert(connection: &mut Connection, profile: &MachineProfile) -> Result<(), String> {
    validate_profile(profile)?;
    let tx = connection
        .transaction_with_behavior(TransactionBehavior::Immediate)
        .map_err(|error| error.to_string())?;
    let existing_created: Option<i64> = tx
        .query_row(
            "SELECT created_at_ms FROM machine_profiles WHERE id = ?1",
            [&profile.id],
            |row| row.get(0),
        )
        .optional()
        .map_err(|error| error.to_string())?;
    let mut stored = profile.clone();
    if let Some(created_at_ms) = existing_created {
        stored.created_at_ms = created_at_ms;
    }
    let document_json = serde_json::to_string(&stored).map_err(|error| error.to_string())?;
    tx.execute(
        "INSERT INTO machine_profiles(id,name,document_json,created_at_ms,updated_at_ms)
         VALUES (?1,?2,?3,?4,?5)
         ON CONFLICT(id) DO UPDATE SET name=excluded.name, document_json=excluded.document_json,
             updated_at_ms=excluded.updated_at_ms",
        params![
            stored.id,
            stored.name,
            document_json,
            stored.created_at_ms,
            stored.updated_at_ms
        ],
    )
    .map_err(|error| error.to_string())?;
    tx.commit().map_err(|error| error.to_string())
}

/// Deletes one profile by local id, clearing its durable active selection if necessary.
pub fn delete(connection: &Connection, id: &str) -> Result<bool, String> {
    let tx = connection
        .unchecked_transaction()
        .map_err(|error| error.to_string())?;
    let changed = tx
        .execute("DELETE FROM machine_profiles WHERE id = ?1", [id])
        .map_err(|error| error.to_string())?;
    if changed != 0 {
        tx.execute(
            "DELETE FROM machine_profile_settings WHERE key='active_profile_id' AND value=?1",
            [id],
        )
        .map_err(|error| error.to_string())?;
    }
    tx.commit().map_err(|error| error.to_string())?;
    Ok(changed != 0)
}

/// Reads the durable local profile selection without consulting a controller or issuing commands.
pub fn active_profile_id(connection: &Connection) -> Result<Option<String>, String> {
    connection
        .query_row(
            "SELECT value FROM machine_profile_settings WHERE key='active_profile_id'",
            [],
            |row| row.get(0),
        )
        .optional()
        .map_err(|error| error.to_string())
}

/// Stores or clears the active local profile id after confirming that the referenced profile exists.
pub fn select_profile(connection: &Connection, id: Option<&str>) -> Result<(), String> {
    if let Some(id) = id {
        let exists: bool = connection
            .query_row(
                "SELECT EXISTS(SELECT 1 FROM machine_profiles WHERE id=?1)",
                [id],
                |row| row.get(0),
            )
            .map_err(|error| error.to_string())?;
        if !exists {
            return Err("machine profile does not exist".into());
        }
        connection.execute("INSERT INTO machine_profile_settings(key,value) VALUES ('active_profile_id',?1) ON CONFLICT(key) DO UPDATE SET value=excluded.value", [id]).map_err(|error| error.to_string())?;
    } else {
        connection
            .execute(
                "DELETE FROM machine_profile_settings WHERE key='active_profile_id'",
                [],
            )
            .map_err(|error| error.to_string())?;
    }
    Ok(())
}

/// Validates every profile before any import write, then applies the complete document transactionally.
pub fn import_document(
    connection: &mut Connection,
    document: &MachineProfileDocument,
) -> Result<(), String> {
    if document.schema_version != PROFILE_DOCUMENT_VERSION {
        return Err(format!(
            "unsupported machine profile schema version {}",
            document.schema_version
        ));
    }
    if document.profiles.len() > 500 {
        return Err("machine profile document exceeds the 500 profile limit".into());
    }
    let mut ids = HashSet::new();
    let mut names = HashSet::new();
    for profile in &document.profiles {
        validate_profile(profile)?;
        if !ids.insert(profile.id.as_str()) {
            return Err(format!("duplicate machine profile id `{}`", profile.id));
        }
        if !names.insert(profile.name.trim().to_lowercase()) {
            return Err(format!("duplicate machine profile name `{}`", profile.name));
        }
    }
    let tx = connection
        .transaction_with_behavior(TransactionBehavior::Immediate)
        .map_err(|error| error.to_string())?;
    for profile in &document.profiles {
        let json = serde_json::to_string(profile).map_err(|error| error.to_string())?;
        tx.execute(
            "INSERT INTO machine_profiles(id,name,document_json,created_at_ms,updated_at_ms)
             VALUES (?1,?2,?3,?4,?5)
             ON CONFLICT(id) DO UPDATE SET name=excluded.name, document_json=excluded.document_json,
                 updated_at_ms=excluded.updated_at_ms",
            params![
                profile.id,
                profile.name,
                json,
                profile.created_at_ms,
                profile.updated_at_ms
            ],
        )
        .map_err(|error| error.to_string())?;
    }
    tx.commit().map_err(|error| error.to_string())
}

/// Rejects malformed or ambiguous profile data before it can enter storage or export.
pub fn validate_profile(profile: &MachineProfile) -> Result<(), String> {
    let valid_id = !profile.id.is_empty()
        && profile.id.len() <= 80
        && profile
            .id
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || "_-".contains(ch));
    if !valid_id {
        return Err("machine profile id must be 1-80 ASCII letters, digits, '_' or '-'".into());
    }
    if profile.name.trim().is_empty() || profile.name.trim().len() > 120 {
        return Err("machine profile name must contain 1-120 characters".into());
    }
    for (axis, min, max) in [
        ("X", profile.travel.x_min, profile.travel.x_max),
        ("Y", profile.travel.y_min, profile.travel.y_max),
        ("Z", profile.travel.z_min, profile.travel.z_max),
    ] {
        if min.is_some_and(|value| !value.is_finite())
            || max.is_some_and(|value| !value.is_finite())
        {
            return Err(format!("{axis} travel values must be finite numbers"));
        }
        if let (Some(min), Some(max)) = (min, max) {
            if min >= max {
                return Err(format!(
                    "{axis} travel minimum must be less than its maximum"
                ));
            }
        }
    }
    for speed in [profile.speeds.x, profile.speeds.y, profile.speeds.z]
        .into_iter()
        .flatten()
    {
        if !speed.is_finite() || speed <= 0.0 {
            return Err("axis speeds must be finite positive numbers".into());
        }
    }
    if profile.tool_reference.as_deref().is_some_and(|id| {
        id.is_empty()
            || id.len() > 80
            || !id
                .chars()
                .all(|ch| ch.is_ascii_alphanumeric() || "_-".contains(ch))
    }) {
        return Err("tool reference must be a valid local tool id".into());
    }
    if let Some(power) = &profile.power {
        for value in [power.min, power.max].into_iter().flatten() {
            if !value.is_finite() || value < 0.0 {
                return Err("power profile values must be finite and non-negative".into());
            }
        }
        if let (Some(min), Some(max)) = (power.min, power.max) {
            if min >= max {
                return Err("power profile minimum must be less than its maximum".into());
            }
        }
    }
    if profile.created_at_ms < 0 || profile.updated_at_ms < profile.created_at_ms {
        return Err("machine profile timestamps are invalid".into());
    }
    let extensions_size = serde_json::to_vec(&profile.extensions)
        .map_err(|error| error.to_string())?
        .len();
    if extensions_size > 65_536 {
        return Err("machine profile extensions exceed 65536 bytes".into());
    }
    Ok(())
}

/// Encodes profiles into the stable, versioned JSON export envelope.
pub fn export_document(profiles: Vec<MachineProfile>) -> MachineProfileDocument {
    MachineProfileDocument {
        schema_version: PROFILE_DOCUMENT_VERSION,
        profiles,
    }
}

